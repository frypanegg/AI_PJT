def set_text(shape, text, size=None):
    """첫 run의 텍스트만 교체해 원본 서식을 유지한다."""
    tf = shape.text_frame
    para = tf.paragraphs[0]
    if not para.runs:
        r = para.add_run()
        r.text = text
    else:
        para.runs[0].text = text
        for extra in para.runs[1:]:
            extra._r.getparent().remove(extra._r)
    for p in tf.paragraphs[1:]:
        p._p.getparent().remove(p._p)
    if size:
        for r in tf.paragraphs[0].runs:
            r.font.size = Pt(size)


def fill_body(shape, items, size=28, gap=10):
    """빈 콘텐츠 자리표시자를 문단 목록으로 채운다.

    items: 문자열 또는 (제목, 설명) 튜플. 튜플이면 제목을 굵게 낸다.
    """
    tf = shape.text_frame
    tf.word_wrap = True
    for p in list(tf.paragraphs)[1:]:
        p._p.getparent().remove(p._p)
    base = tf.paragraphs[0]
    for r in list(base.runs):
        r._r.getparent().remove(r._r)

    first = True
    for it in items:
        para = base if first else tf.add_paragraph()
        first = False
        para.space_after = Pt(gap)
        if isinstance(it, tuple):
            head, body = it
            r1 = para.add_run(); r1.text = head
            r1.font.bold = True; r1.font.size = Pt(size); r1.font.name = "Pretendard"
            if body:
                r2 = para.add_run(); r2.text = "   " + body
                r2.font.size = Pt(size - 4); r2.font.name = "Pretendard Medium"
        else:
            r = para.add_run(); r.text = it
            r.font.size = Pt(size); r.font.name = "Pretendard Medium"


def bars(slide):
    """4행 바 슬라이드에서 (제목 자리, 본문 텍스트박스 4개)를 골라낸다.

    양식에는 첫 바 위에 빈 텍스트 상자가 하나 더 겹쳐 있다. 위치로만 정렬하면
    그 상자가 두 번째로 잡혀 마지막 바가 비므로, 실제 자리표시자 문구가 든
    상자만 골라 쓴다.
    """
    title = slide.shapes[0]
    boxes = [sh for sh in slide.shapes
             if sh.has_text_frame and sh.shape_type is not None
             and "TEXT_BOX" in str(sh.shape_type)
             and sh.text_frame.text.strip()]
    boxes.sort(key=lambda s: s.top)
    return title, boxes


